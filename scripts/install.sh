#!/usr/bin/env bash
# Install PROVE from a built tree. Run as root inside the target system.
#
# usage: scripts/install.sh [--profile debug|release] [--test-vm] [--mode audit|enforce]
#   --test-vm   additionally apply the test-VM preconditions: desktop user gets access to
#               /dev/uinput and /dev/uhid (the attack precondition, SPEC section 3)
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
profile=debug; test_vm=0; mode=""
while (( $# )); do
    case "$1" in
        --profile) profile="$2"; shift 2 ;;
        --test-vm) test_vm=1; shift ;;
        --mode) mode="$2"; shift 2 ;;
        *) echo "unknown option $1" >&2; exit 64 ;;
    esac
done
(( EUID == 0 )) || { echo "must run as root" >&2; exit 1; }
bin="$root/target/$profile"
for b in provd provectl prove-consent prove-requester-demo; do
    [[ -x "$bin/$b" ]] || { echo "$bin/$b missing: build first" >&2; exit 1; }
done

systemctl stop provd 2>/dev/null || true

install -d -m 0755 /usr/libexec/prove /etc/prove /usr/share/doc/prove
install -m 0755 -o root -g root "$bin/provd" "$bin/provectl" "$bin/prove-requester-demo" /usr/bin/
install -m 0755 -o root -g root "$bin/prove-consent" /usr/libexec/prove/
install -m 0644 "$root/SPEC.md" /usr/share/doc/prove/
install -m 0644 "$root/config/provd.service" /etc/systemd/system/provd.service
install -m 0644 "$root/config/prove-sysusers.conf" /usr/lib/sysusers.d/prove.conf
install -m 0644 "$root/config/prove-modules.conf" /etc/modules-load.d/prove.conf
systemd-sysusers /usr/lib/sysusers.d/prove.conf
modprobe -a uinput uhid hid

[[ -f /etc/prove/provd.toml ]] || install -m 0644 "$root/config/provd.toml" /etc/prove/provd.toml
[[ -f /etc/prove/allow-inject.toml ]] || install -m 0644 "$root/config/allow-inject.toml.example" /etc/prove/allow-inject.toml
if [[ -n "$mode" ]]; then
    sed -i "s/^mode = .*/mode = \"$mode\"/" /etc/prove/provd.toml
fi

# The demo requester is always listed, with the hash of the binary just installed.
cat > /etc/prove/requesters.toml <<TOML
# Generated by scripts/install.sh. See config/requesters.toml.example.
[[requester]]
name   = "prove-requester-demo"
path   = "/usr/bin/prove-requester-demo"
sha256 = "$(sha256sum /usr/bin/prove-requester-demo | cut -d' ' -f1)"
TOML
chmod 0644 /etc/prove/requesters.toml

if (( test_vm )); then
    getent group prove-attacker >/dev/null || groupadd --system prove-attacker
    for u in $(awk -F: '$3>=1000 && $3<60000 {print $1}' /etc/passwd); do
        usermod -aG prove-attacker "$u"
    done
    install -m 0644 "$root/config/70-prove-test-uinput.rules" /etc/udev/rules.d/
    udevadm control --reload
    udevadm trigger --action=add /dev/uinput /dev/uhid 2>/dev/null || udevadm trigger
fi

systemctl daemon-reload
systemctl enable --now provd
sleep 1
provectl status
